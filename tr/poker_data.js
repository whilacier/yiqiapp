  // 构建 54 张牌数据数组
  function buildPokerCards() {
    var suits = [
      { key:'ht', folder:'ht', label:'黑桃' },
      { key:'hx', folder:'hx', label:'红心' },
      { key:'fk', folder:'fk', label:'方块' },
      { key:'mh', folder:'mh', label:'梅花' }
    ];
    var ranks = ['a','2','3','4','5','6','7','8','9','10','j','q','k'];
    var list = [];
    suits.forEach(function (s) {
      ranks.forEach(function (r) {
        var id = s.key + '_' + r;
        var m = MEANING[id] || { name: s.label + r.toUpperCase(), up:'', rev:'' };
        list.push({
          id: id,
          name: m.name,
          group: s.label,          // 花色名（黑桃/红心/方块/梅花），供弹层组名显示
          suit: s.label,
          rank: r.toUpperCase(),
          image_path: 'poc/' + s.folder + r + '.jpg',
          upright_meaning: m.up,
          reversed_meaning: m.rev
        });
      });
    });
    // 大小王
    list.push({ id:'dw', name:'大王', group:'王牌', suit:'王牌', rank:'DW', image_path:'poc/dw.jpg', upright_meaning:MEANING['dw'].up, reversed_meaning:MEANING['dw'].rev });
    list.push({ id:'xw', name:'小王', group:'王牌', suit:'王牌', rank:'XW', image_path:'poc/xw.jpg', upright_meaning:MEANING['xw'].up, reversed_meaning:MEANING['xw'].rev });
    return list;
  }

